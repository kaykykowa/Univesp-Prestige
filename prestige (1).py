import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import os

from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import silhouette_score
from google.colab import files

# 1. CARREGAR O EXCEL TRATADO

arquivo = "Prestige_Dados_Tratados.xlsx"

if not os.path.exists(arquivo):
    print("Selecione o Excel tratado anteriormente.")
    enviados = files.upload()
    arquivo = next(
        (nome for nome in enviados if nome.lower().endswith(".xlsx")),
        None
    )
    if arquivo is None:
        raise ValueError("Nenhum arquivo XLSX enviado.")

vendas = pd.read_excel(arquivo, sheet_name="Vendas_Tratadas")
clientes = pd.read_excel(arquivo, sheet_name="Clientes_RFM")
inconsistencias = pd.read_excel(
    arquivo, sheet_name="Inconsistencias"
)

print("Clientes carregados:", len(clientes))

# 2. SELECIONAR VARIÁVEIS RFM

variaveis = [
    "recencia_dias",
    "frequencia_registros",
    "valor_preco_registrado"
]

dados = clientes.dropna(subset=variaveis).copy()

# K-Means precisa de valores válidos.
dados = dados[
    (dados["recencia_dias"] >= 0) &
    (dados["frequencia_registros"] > 0) &
    (dados["valor_preco_registrado"] >= 0)
].copy()

print("Clientes aptos ao modelo:", len(dados))

if len(dados) < 4:
    raise ValueError("Dados insuficientes para testar clusters.")

# 3. TRANSFORMAR E PADRONIZAR OS DADOS
# log1p reduz o efeito de valores muito elevados.
# StandardScaler coloca as variáveis na mesma escala.

X_log = np.log1p(dados[variaveis])

scaler = StandardScaler()
X = scaler.fit_transform(X_log)

# 4. TESTAR QUANTIDADES DE CLUSTERS

quantidades = []
silhouettes = []
inercias = []

max_clusters = min(8, len(dados) - 1)
distintos = len(np.unique(X, axis=0))
max_clusters = min(max_clusters, distintos - 1)

if max_clusters < 2:
    raise ValueError(
        "Pouca diversidade nos dados para segmentação."
    )

for k in range(2, max_clusters + 1):

    modelo = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=20
    )

    grupos = modelo.fit_predict(X)
    n_grupos = len(np.unique(grupos))

    if 2 <= n_grupos < len(X):
        score = silhouette_score(X, grupos)
    else:
        score = np.nan

    quantidades.append(k)
    silhouettes.append(score)
    inercias.append(modelo.inertia_)

resultados = pd.DataFrame({
    "clusters": quantidades,
    "silhouette_score": silhouettes,
    "inercia": inercias
})

print("\nAVALIAÇÃO DOS MODELOS")
display(resultados)

# 5. ESCOLHER MELHOR K PELO SILHOUETTE

validos = resultados.dropna(subset=["silhouette_score"])

if validos.empty:
    raise ValueError("Não foi possível avaliar os agrupamentos.")

melhor_k = int(
    validos.loc[
        validos["silhouette_score"].idxmax(),
        "clusters"
    ]
)

print("\nQuantidade selecionada de clusters:", melhor_k)

# 6. TREINAR MODELO FINAL

modelo_final = KMeans(
    n_clusters=melhor_k,
    random_state=42,
    n_init=20
)

dados["cluster"] = modelo_final.fit_predict(X)

# 7. ANALISAR PERFIL DOS CLUSTERS

perfil = dados.groupby("cluster").agg(
    clientes=("cliente_id", "count"),
    recencia_media=("recencia_dias", "mean"),
    frequencia_media=("frequencia_registros", "mean"),
    valor_medio=("valor_preco_registrado", "mean"),
    valor_total=("valor_preco_registrado", "sum")
).reset_index()

perfil["percentual_clientes"] = (
    perfil["clientes"] / len(dados) * 100
)

perfil = perfil.round(2).sort_values("cluster")

print("\nPERFIL DOS CLUSTERS")
display(perfil)

# 8. GRÁFICO DE AVALIAÇÃO

plt.figure(figsize=(9, 5))

plt.plot(
    resultados["clusters"],
    resultados["silhouette_score"],
    marker="o"
)

plt.axvline(
    melhor_k,
    linestyle="--",
    label=f"K selecionado = {melhor_k}"
)

plt.title("Avaliação do K-Means - Silhouette Score")
plt.xlabel("Quantidade de clusters")
plt.ylabel("Silhouette Score")
plt.legend()
plt.grid(alpha=0.3)
plt.show()

# 9. VISUALIZAR DISTRIBUIÇÃO DOS CLIENTES

