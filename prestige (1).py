def converter_numero(valor):
    if pd.isna(valor):
        return np.nan

    if isinstance(valor, (int, float, np.number)):
        return float(valor)

    texto = str(valor).strip()
    texto = texto.replace("R$", "")
    texto = re.sub(r"\s+", "", texto)

    if "," in texto:
        texto = texto.replace(".", "").replace(",", ".")

    return pd.to_numeric(texto, errors="coerce")


for coluna in numericas:
    df[coluna] = df[coluna].apply(converter_numero)


# 6. CRIAR IDENTIFICADOR DO CLIENTE
# O nome original será retirado do arquivo exportado.

def gerar_id(nome):
    if pd.isna(nome):
        return ""

    chave = " ".join(str(nome).casefold().split())

    codigo = hashlib.sha256(
        chave.encode("utf-8")
    ).hexdigest()[:12]

    return "CLI_" + codigo.upper()


df["cliente_id"] = df["cliente"].apply(gerar_id)


# 7. IDENTIFICAR INCONSISTÊNCIAS

def verificar(linha):
    erros = []

    if pd.isna(linha["cliente"]):
        erros.append("cliente_ausente")

    if pd.isna(linha["produto"]):
        erros.append("produto_ausente")

    if pd.isna(linha["data"]):
        erros.append("data_invalida")

    elif (
        linha["data"].year < 2020
        or linha["data"].year > 2026
    ):
        erros.append("data_atipica")

    if pd.notna(linha["cliente"]):
        if str(linha["cliente"]).strip().lower() == "teste":
            erros.append("cliente_teste")

    if (
        pd.isna(linha["quantidade"])
        or linha["quantidade"] <= 0
    ):
        erros.append("quantidade_invalida")

    if (
        pd.isna(linha["preco"])
        or linha["preco"] < 0
    ):
        erros.append("preco_invalido")

    if pd.isna(linha["lucro"]):
        erros.append("lucro_ausente")

    if (
        pd.notna(linha["a_receber"])
        and linha["a_receber"] < 0
    ):
        erros.append("a_receber_negativo")

    return " | ".join(erros)


